CREATE OR ALTER PROCEDURE dbo.FI_SP_ConsCliente
    @ID BIGINT
AS
BEGIN
    SET NOCOUNT ON;

    IF ISNULL(@ID, 0) = 0
    BEGIN
        SELECT ID, NOME, SOBRENOME, NACIONALIDADE, CEP, ESTADO, CIDADE, LOGRADOURO, EMAIL, TELEFONE, CPF
        FROM dbo.CLIENTES WITH (NOLOCK);
    END
    ELSE
    BEGIN
        SELECT ID, NOME, SOBRENOME, NACIONALIDADE, CEP, ESTADO, CIDADE, LOGRADOURO, EMAIL, TELEFONE, CPF
        FROM dbo.CLIENTES WITH (NOLOCK)
        WHERE ID = @ID;
    END;
END;
