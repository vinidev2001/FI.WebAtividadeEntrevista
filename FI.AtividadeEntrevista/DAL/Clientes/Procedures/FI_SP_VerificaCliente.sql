CREATE OR ALTER PROCEDURE dbo.FI_SP_VerificaCliente
    @CPF VARCHAR(11),
    @ID BIGINT = 0
AS
BEGIN
    SET NOCOUNT ON;

    SELECT CAST(CASE WHEN EXISTS (
        SELECT 1
        FROM dbo.CLIENTES WITH (NOLOCK)
        WHERE CPF = @CPF AND (@ID = 0 OR ID <> @ID)
    ) THEN 1 ELSE 0 END AS BIT);
END;
