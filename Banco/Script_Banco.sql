IF COL_LENGTH('dbo.CLIENTES', 'CPF') IS NULL
    ALTER TABLE dbo.CLIENTES ADD CPF VARCHAR(11) NULL;
GO

IF OBJECT_ID('dbo.BENEFICIARIOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.BENEFICIARIOS
    (
        ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_BENEFICIARIOS PRIMARY KEY,
        CPF VARCHAR(11) NOT NULL,
        NOME VARCHAR(255) NOT NULL,
        IDCLIENTE BIGINT NOT NULL,
        CONSTRAINT FK_BENEFICIARIOS_CLIENTES FOREIGN KEY (IDCLIENTE)
            REFERENCES dbo.CLIENTES(ID) ON DELETE CASCADE
    );
END;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='UX_CLIENTES_CPF' AND object_id=OBJECT_ID('dbo.CLIENTES'))
    CREATE UNIQUE INDEX UX_CLIENTES_CPF ON dbo.CLIENTES(CPF) WHERE CPF IS NOT NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='UX_BENEFICIARIOS_CLIENTE_CPF' AND object_id=OBJECT_ID('dbo.BENEFICIARIOS'))
    CREATE UNIQUE INDEX UX_BENEFICIARIOS_CLIENTE_CPF ON dbo.BENEFICIARIOS(IDCLIENTE, CPF);
GO
CREATE OR ALTER PROCEDURE dbo.FI_SP_AltBeneficiario
    @ID BIGINT,
    @CPF VARCHAR(11),
    @NOME VARCHAR(255),
    @IDCLIENTE BIGINT
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE dbo.BENEFICIARIOS
    SET CPF = @CPF, NOME = @NOME
    WHERE ID = @ID AND IDCLIENTE = @IDCLIENTE;
END;

GO

